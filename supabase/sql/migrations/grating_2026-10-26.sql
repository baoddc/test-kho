-- =============================================================================
-- PHÂN HỆ GRATING (2026-10-26)
--
-- Grating nhập / xuất theo KG (không có Cuộn ID). Tồn kho tính theo
-- (Mã vật tư, Batch) = tổng nhập − tổng xuất, lưu ở bảng "grating-ton" do trigger
-- cập nhật ngay khi nhập / xuất thay đổi. Không cho xuất vượt tồn, không cho sửa /
-- xóa phiếu nhập làm tồn âm.
--
-- Yêu cầu: đã chạy scale_1m_rows_2026-10-20.sql (hàm _qry_*, qry_rows, dashboard_kho).
-- Chạy lại nhiều lần vẫn an toàn.
-- =============================================================================


-- =============================================================================
-- 1. BẢNG NHẬP / XUẤT (cùng cột với xà gồ, bỏ Cuộn ID)
-- =============================================================================

create table if not exists public."grating-nhap" (
  id bigint generated by default as identity primary key,
  "Mã chứng từ" text,
  "Ngày nhập" date,
  "Phiếu nhập" text,
  "Loại nhập" text,
  "Mã vật tư" text,
  "Tên vật tư" text,
  "Batch" text,
  "Số lượng (Kg)" numeric,
  "Vị trí" text,
  "Mã công trình" text,
  "Tên công trình" text,
  "Ghi chú" text,
  created_at timestamptz default now(),
  constraint grating_nhap_kg_duong check ("Số lượng (Kg)" is null or "Số lượng (Kg)" > 0)
);

create table if not exists public."grating-xuat" (
  id bigint generated by default as identity primary key,
  "Mã chứng từ" text,
  "Ngày xuất" date,
  "Phiếu xuất" text,
  "Loại xuất" text,
  "Mã vật tư" text,
  "Tên vật tư" text,
  "Batch" text,
  "Số lượng (Kg)" numeric,
  "Mã công trình" text,
  "Tên công trình" text,
  "Ghi chú" text,
  created_at timestamptz default now(),
  constraint grating_xuat_kg_duong check ("Số lượng (Kg)" is null or "Số lượng (Kg)" > 0)
);

-- Khóa tồn kho của 1 dòng: Mã vật tư + Batch (không phân biệt hoa thường / khoảng trắng)
create or replace function public.grating_key(p_ma text, p_batch text)
returns text language sql immutable parallel safe as $$
  select lower(trim(coalesce(p_ma, ''))) || '|' || lower(trim(coalesce(p_batch, '')))
$$;

create index if not exists idx_grating_nhap_key on public."grating-nhap" (public.grating_key("Mã vật tư", "Batch"));
create index if not exists idx_grating_xuat_key on public."grating-xuat" (public.grating_key("Mã vật tư", "Batch"));


-- =============================================================================
-- 2. BẢNG TỒN "grating-ton" (1 dòng / Mã vật tư + Batch)
--    "Ngày nhập" = ngày nhập của lô cũ nhất còn tồn (xuất theo FIFO),
--    "Vị trí" = các vị trí của những lô còn tồn.
-- =============================================================================

create table if not exists public."grating-ton" (
  id bigint generated by default as identity primary key,
  ton_key text not null unique,
  "Mã vật tư" text,
  "Tên vật tư" text,
  "Batch" text,
  "Nhập (Kg)" numeric not null default 0,
  "Xuất (Kg)" numeric not null default 0,
  "Số lượng (Kg)" numeric not null default 0,
  "Ngày nhập" date,
  "Vị trí" text,
  "Mã công trình" text,
  "Tên công trình" text,
  updated_at timestamptz not null default now()
);

-- Tính lại 1 khóa tồn từ dữ liệu gốc (khóa advisory theo khóa tồn để 2 phiếu xuất
-- cùng lúc không cùng vượt tồn). Tồn âm → báo lỗi và hủy thao tác.
create or replace function public._grating_ton_refresh(p_key text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nhap numeric;
  v_xuat numeric;
  v_n_count bigint;
  v_x_count bigint;
  v_ton numeric;
  v_ma text;
  v_ten text;
  v_batch text;
  v_ngay date;
  v_vitri text;
  v_mact text;
  v_tenct text;
begin
  if p_key is null then return; end if;
  perform pg_advisory_xact_lock(hashtext('grating-ton:' || p_key));

  select coalesce(sum("Số lượng (Kg)"), 0), count(*) into v_nhap, v_n_count
    from public."grating-nhap" where public.grating_key("Mã vật tư", "Batch") = p_key;
  select coalesce(sum("Số lượng (Kg)"), 0), count(*) into v_xuat, v_x_count
    from public."grating-xuat" where public.grating_key("Mã vật tư", "Batch") = p_key;

  if v_n_count = 0 and v_x_count = 0 then
    delete from public."grating-ton" where ton_key = p_key;
    return;
  end if;

  -- Tên hiển thị lấy từ dòng nhập mới nhất (không có nhập thì từ dòng xuất)
  select trim("Mã vật tư"), trim("Batch") into v_ma, v_batch
    from (select "Mã vật tư", "Batch", id, 1 as src from public."grating-nhap" where public.grating_key("Mã vật tư", "Batch") = p_key
          union all
          select "Mã vật tư", "Batch", id, 2 from public."grating-xuat" where public.grating_key("Mã vật tư", "Batch") = p_key) u
   order by src, id desc limit 1;

  v_ton := v_nhap - v_xuat;
  if v_ton < -0.0005 then
    raise exception 'Grating % (Batch: %) không đủ tồn: đã nhập % kg, xuất % kg (thiếu % kg).',
      coalesce(nullif(v_ma, ''), '(trống)'), coalesce(nullif(v_batch, ''), '(trống)'),
      round(v_nhap, 3), round(v_xuat, 3), round(-v_ton, 3)
      using errcode = 'P0001';
  end if;

  select trim("Tên vật tư") into v_ten
    from public."grating-nhap"
   where public.grating_key("Mã vật tư", "Batch") = p_key and trim(coalesce("Tên vật tư", '')) <> ''
   order by id desc limit 1;
  if v_ten is null then
    select trim("Tên vật tư") into v_ten
      from public."grating-xuat"
     where public.grating_key("Mã vật tư", "Batch") = p_key and trim(coalesce("Tên vật tư", '')) <> ''
     order by id desc limit 1;
  end if;

  -- Lô còn tồn theo FIFO: các dòng nhập mới nhất có tổng vừa đủ phủ số tồn
  if v_ton > 0.0005 then
    with n as (
      select "Ngày nhập" as d, trim(coalesce("Vị trí", '')) as vt, "Số lượng (Kg)" as kg,
             trim(coalesce("Mã công trình", '')) as mact, trim(coalesce("Tên công trình", '')) as tenct, id,
             sum(coalesce("Số lượng (Kg)", 0)) over (order by "Ngày nhập" desc nulls last, id desc) as cum
        from public."grating-nhap"
       where public.grating_key("Mã vật tư", "Batch") = p_key
    ), con as (
      select * from n where cum - coalesce(kg, 0) < v_ton
    )
    select min(d),
           string_agg(distinct vt, ', ') filter (where vt <> ''),
           (select mact from con where mact <> '' order by id desc limit 1),
           (select tenct from con where tenct <> '' order by id desc limit 1)
      into v_ngay, v_vitri, v_mact, v_tenct
      from con;
  end if;

  insert into public."grating-ton" as t (ton_key, "Mã vật tư", "Tên vật tư", "Batch", "Nhập (Kg)", "Xuất (Kg)",
                                         "Số lượng (Kg)", "Ngày nhập", "Vị trí", "Mã công trình", "Tên công trình", updated_at)
  values (p_key, v_ma, v_ten, v_batch, v_nhap, v_xuat, greatest(v_ton, 0), v_ngay, v_vitri, v_mact, v_tenct, now())
  on conflict (ton_key) do update
    set "Mã vật tư" = excluded."Mã vật tư", "Tên vật tư" = excluded."Tên vật tư", "Batch" = excluded."Batch",
        "Nhập (Kg)" = excluded."Nhập (Kg)", "Xuất (Kg)" = excluded."Xuất (Kg)", "Số lượng (Kg)" = excluded."Số lượng (Kg)",
        "Ngày nhập" = excluded."Ngày nhập", "Vị trí" = excluded."Vị trí",
        "Mã công trình" = excluded."Mã công trình", "Tên công trình" = excluded."Tên công trình",
        updated_at = now();
end $$;

create or replace function public.trg_grating_ton()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_new text;
  v_old text;
begin
  if tg_op in ('INSERT', 'UPDATE') then
    v_new := public.grating_key(new."Mã vật tư", new."Batch");
  end if;
  if tg_op in ('UPDATE', 'DELETE') then
    v_old := public.grating_key(old."Mã vật tư", old."Batch");
  end if;

  -- Khóa theo thứ tự cố định để 2 giao dịch đổi khóa ngược chiều không bị deadlock
  if v_old is not null and v_new is not null and v_old <> v_new then
    perform public._grating_ton_refresh(least(v_old, v_new));
    perform public._grating_ton_refresh(greatest(v_old, v_new));
  else
    perform public._grating_ton_refresh(coalesce(v_new, v_old));
  end if;
  return null;
end $$;

drop trigger if exists trg_grating_ton on public."grating-nhap";
create trigger trg_grating_ton after insert or update or delete on public."grating-nhap"
  for each row execute function public.trg_grating_ton();
drop trigger if exists trg_grating_ton on public."grating-xuat";
create trigger trg_grating_ton after insert or update or delete on public."grating-xuat"
  for each row execute function public.trg_grating_ton();

-- Dựng lại tồn từ dữ liệu hiện có (lần đầu bảng rỗng; chạy lại để đồng bộ nếu cần)
do $$
declare k text;
begin
  for k in
    select public.grating_key("Mã vật tư", "Batch") from public."grating-nhap"
    union
    select public.grating_key("Mã vật tư", "Batch") from public."grating-xuat"
  loop
    perform public._grating_ton_refresh(k);
  end loop;
  delete from public."grating-ton" t
   where not exists (select 1 from public."grating-nhap" n where public.grating_key(n."Mã vật tư", n."Batch") = t.ton_key)
     and not exists (select 1 from public."grating-xuat" x where public.grating_key(x."Mã vật tư", x."Batch") = t.ton_key);
end $$;


